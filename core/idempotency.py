"""
Deterministic idempotency key generator for migration records.
"""
from __future__ import annotations

import hashlib
import json
from typing import Any


def generate_key(plan_id: str, source_record: dict[str, Any], row_index: int) -> str:
    """
    Generate a deterministic SHA-256 idempotency key for a source record within a migration plan.

    The key is generated by computing the SHA-256 hash of a canonical JSON string
    containing:
      - plan_id: Unique identifier of the migration plan
      - sorted record items: Key-value pairs of source_record sorted by key
      - row_index: Zero-based position of the record in the source dataset

    This key is stored with each target record to satisfy UNIQUE constraints and
    prevent duplicate insertions on migration retries.

    Args:
        plan_id: The ID of the migration plan.
        source_record: The raw source dictionary for the record.
        row_index: The index of the row within the sample/source batch.

    Returns:
        A 64-character hexadecimal SHA-256 hash string.
    """
    # Sort items deterministically
    sorted_items = sorted(source_record.items(), key=lambda kv: str(kv[0]))

    canonical_payload = {
        "plan_id": str(plan_id),
        "record": sorted_items,
        "row_index": int(row_index),
    }

    canonical_json = json.dumps(
        canonical_payload,
        sort_keys=True,
        separators=(",", ":"),
        default=str,
        ensure_ascii=True,
    )

    return hashlib.sha256(canonical_json.encode("utf-8")).hexdigest()
